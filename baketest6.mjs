import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { clone as skeletonClone } from 'three/examples/jsm/utils/SkeletonUtils.js';
import fs from 'fs';
const buf = fs.readFileSync('public/models/spectator-d086fe.glb');
const gltf = await new GLTFLoader().parseAsync(buf.buffer.slice(buf.byteOffset, buf.byteOffset+buf.byteLength), '');
const sc = skeletonClone(gltf.scene);
sc.updateMatrixWorld(true);
let mesh = null; sc.traverse(o => { if (o.isSkinnedMesh && !mesh) mesh = o; });
const sk = mesh.skeleton;
const fmt = (m) => m.elements.map(x => x.toFixed(2)).join(',');
console.log('boneInverses[3]:', fmt(sk.boneInverses[3]));
console.log('bones[3].matrixWorld:', fmt(sk.bones[3].matrixWorld));
console.log('bindMatrixInverse:', fmt(mesh.bindMatrixInverse));
const v = new THREE.Vector3(0, 1.24, 0.06);
const M = new THREE.Matrix4().multiplyMatrices(sk.bones[3].matrixWorld, sk.boneInverses[3]);
console.log('M(3):', fmt(M));
const out = v.clone().applyMatrix4(M).applyMatrix4(mesh.bindMatrixInverse);
console.log('v0 via bone3:', out.toArray().map(x=>x.toFixed(2)).join(','));
console.log('bindMatrix det', mesh.bindMatrix.determinant(), 'bindMatrixInverse det', mesh.bindMatrixInverse.determinant());
